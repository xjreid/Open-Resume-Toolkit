#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum PdfRenderError {
    #[error("the saved document cannot be rendered")]
    InvalidContent,
    #[error("the bundled fonts do not support this content")]
    UnsupportedGlyph,
    #[error("the document exceeds the PDF layout limit")]
    LayoutLimit,
    #[error("the document exceeds the PDF byte limit")]
    OutputTooLarge,
    #[error("the PDF renderer is unavailable")]
    Unavailable,
}

// No Debug: generated bytes and text must not enter diagnostics.
pub struct PdfArtifact {
    pub bytes: Vec<u8>,
    pub receipt: PdfRenderReceipt,
}

#[derive(Serialize)]
struct InlineRun {
    text: String,
    bold: bool,
    italic: bool,
    url: Option<String>,
}

#[derive(Serialize)]
struct Paragraph {
    kind: &'static str,
    text: String,
    right: Option<String>,
    runs: Vec<InlineRun>,
    right_runs: Vec<InlineRun>,
    subtitle_runs: Vec<InlineRun>,
    title_runs: Vec<InlineRun>,
    detail_runs: Vec<InlineRun>,
    sticky: bool,
    entry_end: bool,
    body_start: bool,
}

fn normalized(value: &str) -> String {
    value
        .replace("\r\n", "\n")
        .replace('\r', "\n")
        .trim()
        .to_owned()
}

fn inline_runs(value: &str, force_bold: bool, force_italic: bool) -> Vec<InlineRun> {
    ort_documents::parse_inline_text(&normalized(value))
        .into_iter()
        .map(|span| InlineRun {
            text: span.text,
            bold: force_bold || span.bold,
            italic: force_italic || span.italic,
            url: span.url,
        })
        .collect()
}

fn plain_runs(runs: &[InlineRun]) -> String {
    runs.iter().map(|run| run.text.as_str()).collect()
}

fn push_paragraph(
    paragraphs: &mut Vec<Paragraph>,
    kind: &'static str,
    runs: Vec<InlineRun>,
    right_runs: Vec<InlineRun>,
) {
    let text = plain_runs(&runs);
    let right = plain_runs(&right_runs);
    if text.is_empty() && right.is_empty() {
        return;
    }
    paragraphs.push(Paragraph {
        kind,
        text,
        right: (!right.is_empty()).then_some(right),
        runs,
        right_runs,
        subtitle_runs: vec![],
        title_runs: vec![],
        detail_runs: vec![],
        sticky: false,
        entry_end: false,
        body_start: false,
    });
}

fn add(paragraphs: &mut Vec<Paragraph>, kind: &'static str, value: &str) {
    push_paragraph(paragraphs, kind, inline_runs(value, false, false), vec![]);
}

fn link(paragraphs: &mut Vec<Paragraph>, value: &Link) -> Result<(), PdfRenderError> {
    if value.url.chars().any(char::is_whitespace) {
        return Err(PdfRenderError::InvalidContent);
    }
    let label = normalized(&value.label);
    let url = normalized(&value.url);
    let text = if label.is_empty() { url.clone() } else { label };
    push_paragraph(
        paragraphs,
        "link",
        vec![InlineRun {
            text,
            bold: false,
            italic: false,
            url: Some(url),
        }],
        vec![],
    );
    Ok(())
}

fn append_runs(target: &mut Vec<InlineRun>, value: &str, bold: bool, italic: bool) {
    target.extend(inline_runs(value, bold, italic));
}

fn append_separator(target: &mut Vec<InlineRun>, separator: &str) {
    if !target.is_empty() {
        target.push(InlineRun {
            text: separator.to_owned(),
            bold: false,
            italic: false,
            url: None,
        });
    }
}

fn append_link(target: &mut Vec<InlineRun>, value: &Link) -> Result<(), PdfRenderError> {
    if value.url.chars().any(char::is_whitespace) {
        return Err(PdfRenderError::InvalidContent);
    }
    let url = normalized(&value.url);
    let label = normalized(&value.label);
    target.push(InlineRun {
        text: if label.is_empty() { url.clone() } else { label },
        bold: false,
        italic: false,
        url: Some(url),
    });
    Ok(())
}

fn paragraphs(
    document: &ResumeDocument,
    style: DocumentStyle,
) -> Result<Vec<Paragraph>, PdfRenderError> {
    ort_documents::render_plain_text(document).map_err(|_| PdfRenderError::InvalidContent)?;
    let mut out = Vec::new();
    push_paragraph(
        &mut out,
        "name",
        inline_runs(
            &document.contact.full_name,
            style != DocumentStyle::Professional,
            false,
        ),
        vec![],
    );
    if style == DocumentStyle::Plain {
        for value in [
            &document.contact.email,
            &document.contact.phone,
            &document.contact.location,
        ] {
            add(&mut out, "text", value);
        }
    } else {
        let mut contact = Vec::new();
        for value in [
            &document.contact.email,
            &document.contact.phone,
            &document.contact.location,
        ] {
            if !normalized(value).is_empty() {
                append_separator(&mut contact, "  •  ");
                append_runs(&mut contact, value, false, false);
            }
        }
        for value in &document.contact.links {
            append_separator(&mut contact, "  •  ");
            append_link(&mut contact, value)?;
        }
        push_paragraph(&mut out, "contact", contact, vec![]);
    }
    if style == DocumentStyle::Plain {
        for value in &document.contact.links {
            link(&mut out, value)?;
        }
    }
    for section in &document.sections {
        let mut entries = Vec::new();
        for entry in &section.entries {
            let entry_start = entries.len();
            entry_header(&mut entries, entry, style);
            let body_start = entries.len();
            if let Some(body) = entry
                .fields
                .iter()
                .find(|field| field.label == PARAGRAPH_FIELD_LABEL)
                .map(|field| field.value.as_str())
                .filter(|value| !value.trim().is_empty())
            {
                add(&mut entries, "text", body);
            } else {
                for bullet in &entry.bullets {
                    add(&mut entries, "bullet", &bullet.text);
                }
            }
            for value in &entry.links {
                link(&mut entries, value)?;
            }
            let entry_end = entries.len();
            if entry_end > entry_start {
                entries[entry_end - 1].entry_end = true;
                if body_start > entry_start && body_start < entry_end {
                    entries[body_start].body_start = true;
                }
            }
            // Keep ordinary entries intact at page boundaries. Exceptionally
            // large entries remain breakable so they can span pages safely.
            if entry_end > entry_start && entry_end - entry_start <= 10 {
                for paragraph in &mut entries[entry_start..entry_end - 1] {
                    paragraph.sticky = true;
                }
            }
        }
        if !entries.is_empty() {
            push_paragraph(
                &mut out,
                "section",
                inline_runs(&section.heading, true, false),
                vec![],
            );
            out.extend(entries);
        }
    }
    validate_paragraphs(&out, style)?;
    Ok(out)
}

fn validate_paragraphs(out: &[Paragraph], style: DocumentStyle) -> Result<(), PdfRenderError> {
    if out.len() > MAX_LAYOUT_BLOCKS
        || out
            .iter()
            .map(|p| {
                p.text.matches('\n').count()
                    + p.right.as_deref().unwrap_or("").matches('\n').count()
                    + p.subtitle_runs
                        .iter()
                        .map(|r| r.text.matches('\n').count())
                        .sum::<usize>()
            })
            .sum::<usize>()
            > MAX_HARD_BREAKS
    {
        return Err(PdfRenderError::LayoutLimit);
    }
    // Do not silently substitute missing characters. Check all selected faces:
    // headings and ordinary text must both have coverage. No system fallback.
    for c in out
        .iter()
        .flat_map(|p| {
            p.text
                .chars()
                .chain(p.right.as_deref().unwrap_or("").chars())
                .chain(p.subtitle_runs.iter().flat_map(|r| r.text.chars()))
        })
        .filter(|c| !c.is_whitespace())
    {
        let covers = |fonts: &[Font]| {
            fonts
                .iter()
                .all(|font| font.info().coverage.contains(u32::from(c)))
        };
        let supported = match style {
            DocumentStyle::Modern => covers(&FONTS[6..10]),
            DocumentStyle::Technical => covers(&FONTS[10..14]),
            // Fixed fallback retains Greek/Cyrillic coverage without host fonts.
            DocumentStyle::Professional => covers(&FONTS[14..18]) || covers(&FONTS[10..14]),
            DocumentStyle::Plain => covers(&FONTS[..6]),
        };
        if !supported {
            return Err(PdfRenderError::UnsupportedGlyph);
        }
    }
    Ok(())
}

fn entry_header(
    entries: &mut Vec<Paragraph>,
    entry: &ort_domain::ResumeEntry,
    style: DocumentStyle,
) {
    let mut title = inline_runs(&entry.heading, true, false);
    let mut details_runs = vec![];
    if let Some(details) = entry.fields.iter().find(|field| {
        field.label != PARAGRAPH_FIELD_LABEL
            && !field.label.trim().eq_ignore_ascii_case("extra")
            && !field.value.trim().is_empty()
    }) {
        details_runs = inline_runs(&details.value, false, false);
        append_separator(&mut title, " | ");
        append_runs(&mut title, &details.value, false, false);
    }
    let dates = if style == DocumentStyle::Plain && !entry.date_range.trim().is_empty() {
        entry.date_range.clone()
    } else {
        std::iter::once(entry.date_range.clone())
            .chain(
                entry
                    .dates
                    .iter()
                    .flatten()
                    .map(ort_domain::ResumeDate::display_text),
            )
            .filter(|value| !value.trim().is_empty())
            .collect::<Vec<_>>()
            .join("\n")
    };
    let extras = entry
        .fields
        .iter()
        .filter(|field| {
            field.label.trim().eq_ignore_ascii_case("extra") && !field.value.trim().is_empty()
        })
        .map(|field| field.value.as_str())
        .collect::<Vec<_>>()
        .join("\n");
    if style != DocumentStyle::Plain {
        let right = [entry.location.as_str(), dates.as_str(), extras.as_str()]
            .into_iter()
            .filter(|value| !value.trim().is_empty())
            .collect::<Vec<_>>()
            .join("\n");
        let subtitle = inline_runs(&entry.subheading, false, false);
        if !title.is_empty() || !subtitle.is_empty() || !right.is_empty() {
            let index = entries.len();
            // One pair of independent stacks: a wrapped title must not move
            // the location/dates down. The body still follows both stacks.
            if title.is_empty() && right.is_empty() {
                push_paragraph(entries, "entry", subtitle, vec![]);
            } else {
                push_paragraph(entries, "entry", title, inline_runs(&right, false, false));
                entries[index].subtitle_runs = subtitle;
                entries[index].title_runs = inline_runs(&entry.heading, true, false);
                entries[index].detail_runs = details_runs;
            }
        }
        return;
    }
    let mut right_rows = [entry.location.as_str(), dates.as_str(), extras.as_str()]
        .into_iter()
        .map(|value| inline_runs(value, false, false))
        .filter(|runs| !runs.is_empty());

    push_paragraph(
        entries,
        "entry",
        title,
        right_rows.next().unwrap_or_default(),
    );
    push_paragraph(
        entries,
        "subrow",
        inline_runs(&entry.subheading, false, false),
        right_rows.next().unwrap_or_default(),
    );
    for right in right_rows {
        push_paragraph(entries, "meta", vec![], right);
    }
}

struct MemoryWorld {
    library: LazyHash<Library>,
    source: Source,
}

impl MemoryWorld {
    fn new(paragraphs: &[Paragraph], style: DocumentStyle) -> Result<Self, PdfRenderError> {
        let json = serde_json::to_string(paragraphs).map_err(|_| PdfRenderError::InvalidContent)?;
        let mut inputs = Dict::new();
        inputs.insert("resume".into(), Value::Str(json.into()));
        Ok(Self {
            library: LazyHash::new(Library::builder().with_inputs(inputs).build()),
            source: match style {
                DocumentStyle::Plain => SOURCE.clone(),
                DocumentStyle::Technical => TECHNICAL_SOURCE.clone(),
                DocumentStyle::Professional => PROFESSIONAL_SOURCE.clone(),
                DocumentStyle::Modern => MODERN_SOURCE.clone(),
            },
        })
    }
}

impl World for MemoryWorld {
    fn library(&self) -> &LazyHash<Library> {
        &self.library
    }
    fn book(&self) -> &LazyHash<FontBook> {
        &BOOK
    }
    fn main(&self) -> FileId {
        self.source.id()
    }
    fn source(&self, id: FileId) -> FileResult<Source> {
        if id == self.source.id() {
            Ok(self.source.clone())
        } else {
            Err(FileError::AccessDenied)
        }
    }
    fn file(&self, id: FileId) -> FileResult<Bytes> {
        if id == self.source.id() {
            Ok(Bytes::from_string(self.source.text().to_owned()))
        } else {
            Err(FileError::AccessDenied)
        }
    }
    fn font(&self, index: usize) -> Option<Font> {
        FONTS.get(index).cloned()
    }
    fn today(&self, _offset: Option<Duration>) -> Option<Datetime> {
        None
    }
}

struct EvictMemoizedContent;
impl Drop for EvictMemoizedContent {
    fn drop(&mut self) {
        comemo::evict(0);
    }
}

#[must_use]
pub fn sha256(bytes: &[u8]) -> String {
    hex::encode(Sha256::digest(bytes))
}

// The reviewed template has only translated groups, text, links and tags.
// Reject overflow after layout (including very long unbreakable words), missing
// shaped glyphs, clipping, images or newly introduced drawing/transform behavior.
fn visible_frame(frame: &Frame, origin: Point, depth: usize) -> bool {
    if depth > 64 {
        return false;
    }
    frame.items().all(|(position, item)| {
        let point = origin + *position;
        match item {
            FrameItem::Group(group) => {
                group.clip.is_none()
                    && group.transform == Transform::identity()
                    && visible_frame(&group.frame, point, depth + 1)
            }
            FrameItem::Text(text) => {
                if text.glyphs.iter().any(|glyph| glyph.id == 0) {
                    return false;
                }
                if text.text.chars().all(char::is_whitespace) {
                    return true;
                }
                let bounds = text.bbox();
                [point + bounds.min, point + bounds.max]
                    .iter()
                    .all(|point| {
                        (32.0..=580.0).contains(&point.x.to_pt())
                            && (28.0..=764.0).contains(&point.y.to_pt())
                    })
            }
            FrameItem::Link(..) | FrameItem::Tag(..) => true,
            FrameItem::Shape(shape, _) => {
                // Only thin, horizontal section rules from bundled templates.
                // Images, fills, curves, clipping and transformed drawing stay denied.
                if let typst::visualize::Geometry::Line(end) = &shape.geometry {
                    shape.fill.is_none()
                        && shape.stroke.as_ref().is_some_and(|stroke| {
                            stroke.thickness.to_pt() > 0.0 && stroke.thickness.to_pt() <= 1.5
                        })
                        && end.y.to_pt() == 0.0
                        && end.x.to_pt() >= 0.0
                        && [point, point + *end].iter().all(|p| {
                            (33.0..=579.0).contains(&p.x.to_pt())
                                && (29.0..=763.0).contains(&p.y.to_pt())
                        })
                } else {
                    false
                }
            }
            FrameItem::Image(..) => false,
        }
    })
}

/// # Errors
/// Refuses invalid content, uncovered glyphs, layout/output limits, and compiler
/// warnings. Error messages never contain template diagnostics or resume text.
pub fn render_pdf(document: &ResumeDocument) -> Result<PdfArtifact, PdfRenderError> {
    render_pdf_with_style(document, DocumentStyle::Plain)
}

/// Renders only a reviewed, compiled-in template. Historical plain output stays
/// byte-identical; receipts identify the selected template and its exact source.
///
/// # Errors
/// Applies the same content, font, geometry, page and byte bounds to every style.
pub fn render_pdf_with_style(
    document: &ResumeDocument,
    style: DocumentStyle,
) -> Result<PdfArtifact, PdfRenderError> {
    let _guard = RENDER_LOCK
        .lock()
        .map_err(|_| PdfRenderError::Unavailable)?;
    let _eviction = EvictMemoizedContent;
    let content = paragraphs(document, style)?;
    let world = MemoryWorld::new(&content, style)?;
    let compiled = typst::compile::<typst_layout::PagedDocument>(&world);
    if !compiled.warnings.is_empty() {
        return Err(PdfRenderError::InvalidContent);
    }
    let output = compiled
        .output
        .map_err(|_| PdfRenderError::InvalidContent)?;
    if output.pages().is_empty() || output.pages().len() > MAX_PDF_PAGES {
        return Err(PdfRenderError::LayoutLimit);
    }
    if !output
        .pages()
        .iter()
        .all(|page| visible_frame(&page.frame, Point::zero(), 0))
    {
        return Err(PdfRenderError::LayoutLimit);
    }
    let bytes = typst_pdf::pdf(
        &output,
        &typst_pdf::PdfOptions {
            creator: Smart::Custom(None),
            ..Default::default()
        },
    )
    .map_err(|_| PdfRenderError::InvalidContent)?;
    if bytes.is_empty() || bytes.len() > MAX_PDF_BYTES {
        return Err(PdfRenderError::OutputTooLarge);
    }
    let mut font_hash = Sha256::new();
    if style == DocumentStyle::Modern {
        for font in MODERN_FONT_BYTES {
            font_hash.update(font);
        }
    } else if style == DocumentStyle::Technical {
        for font in TECHNICAL_FONT_BYTES {
            font_hash.update(font);
        }
    } else if style == DocumentStyle::Professional {
        for font in PROFESSIONAL_FONT_BYTES
            .into_iter()
            .chain(TECHNICAL_FONT_BYTES)
        {
            font_hash.update(font);
        }
    } else {
        for font in typst_assets::fonts().take(6) {
            font_hash.update(font);
        }
    }
    let receipt = PdfRenderReceipt {
        document_sha256: sha256(
            &serde_json::to_vec(document).map_err(|_| PdfRenderError::InvalidContent)?,
        ),
        document_schema_version: document.schema_version,
        pdf_sha256: sha256(&bytes),
        renderer_version: RENDERER_VERSION.into(),
        template_id: style.pdf_template_id().into(),
        template_sha256: sha256(template(style).as_bytes()),
        font_bundle_id: if style == DocumentStyle::Modern {
            MODERN_FONT_BUNDLE_ID
        } else if style == DocumentStyle::Technical {
            TECHNICAL_FONT_BUNDLE_ID
        } else if style == DocumentStyle::Professional {
            PROFESSIONAL_FONT_BUNDLE_ID
        } else {
            FONT_BUNDLE_ID
        }
        .into(),
        font_bundle_sha256: hex::encode(font_hash.finalize()),
        page_count: output.pages().len(),
        byte_count: bytes.len(),
    };
    Ok(PdfArtifact { bytes, receipt })
}

