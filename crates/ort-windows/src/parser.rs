const MAX_EXECUTABLE: u64 = 64 * 1024 * 1024;
const MAX_REQUEST: usize = 10 * 1024 * 1024 + 9;
const MAX_OUTPUT: usize = 512 * 1024;
const MAX_STDERR: usize = 16 * 1024;
const CLEANUP: Duration = Duration::from_secs(2);
// Windows SDK WinBase.h: win32k disable, extension-point disable, dynamic-code
// prohibition. These DWORD64 macros are not generated by windows-sys 0.61.2.
const MITIGATIONS: u64 = (1 << 28) | (1 << 32) | (1 << 36);

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ParserError {
    Identity,
    Containment,
    Io,
    Cancelled,
    Timeout,
    Cleanup,
}
type Result<T> = std::result::Result<T, ParserError>;
#[track_caller]
fn containment() -> ParserError {
    #[cfg(any(test, feature = "test-support"))]
    {
        let location = std::panic::Location::caller();
        // Test-only fixed-site diagnostics; no paths from the user or request bytes.
        let code = unsafe { windows_sys::Win32::Foundation::GetLastError() };
        eprintln!(
            "parser-native: containment check {}:{} (OS code {code})",
            location.file(),
            location.line()
        );
    }
    ParserError::Containment
}
fn wide(value: &OsStr) -> Result<Vec<u16>> {
    let mut value: Vec<_> = value.encode_wide().collect();
    if value.contains(&0) {
        return Err(ParserError::Identity);
    }
    value.push(0);
    Ok(value)
}
fn check(end: Instant, cancel: &AtomicBool) -> Result<()> {
    if cancel.load(Ordering::Acquire) {
        Err(ParserError::Cancelled)
    } else if Instant::now() >= end {
        Err(ParserError::Timeout)
    } else {
        Ok(())
    }
}

struct Container {
    name: Vec<u16>,
    sid: PSID,
    deleted: bool,
}
impl Container {
    fn new() -> Result<Self> {
        let mut bytes = [0; 16];
        getrandom::fill(&mut bytes).map_err(|_| containment())?;
        let name = wide(OsStr::new(&format!(
            "ort.dev.parser.{}",
            hex::encode(bytes)
        )))?;
        let mut sid = null_mut();
        // SAFETY: strings are NUL terminated; zero optional capabilities, owned SID output.
        if unsafe {
            CreateAppContainerProfile(
                name.as_ptr(),
                name.as_ptr(),
                name.as_ptr(),
                null(),
                0,
                &raw mut sid,
            )
        } < 0
        {
            return Err(containment());
        }
        Ok(Self {
            name,
            sid,
            deleted: false,
        })
    }
    fn folder(&self) -> Result<std::path::PathBuf> {
        let mut sid = null_mut();
        // SAFETY: live profile SID; each returned string is freed with its
        // documented allocation family after copying its bounded contents.
        if unsafe { ConvertSidToStringSidW(self.sid, &raw mut sid) } == 0 {
            return Err(containment());
        }
        let mut path = null_mut();
        let status = unsafe { GetAppContainerFolderPath(sid, &raw mut path) };
        unsafe { LocalFree(sid.cast()) };
        if status < 0 || path.is_null() {
            return Err(containment());
        }
        let mut length = 0;
        while length < 32_768 && unsafe { *path.add(length) } != 0 {
            length += 1;
        }
        let result = if length < 32_768 {
            Ok(std::path::PathBuf::from(std::ffi::OsString::from_wide(
                unsafe { std::slice::from_raw_parts(path, length) },
            )))
        } else {
            Err(containment())
        };
        unsafe { CoTaskMemFree(path.cast()) };
        result
    }

    fn grant_read(&self, directory: &Path) -> Result<()> {
        let user = user_sid_string().map_err(|_| containment())?;
        let mut text = null_mut();
        // SAFETY: live SID from CreateAppContainerProfile; LocalFree-owned string output.
        if unsafe { ConvertSidToStringSidW(self.sid, &raw mut text) } == 0 {
            return Err(containment());
        }
        let mut length = 0;
        // SAFETY: Windows SID string has a small bounded NUL-terminated representation.
        while length < 256 && unsafe { *text.add(length) } != 0 {
            length += 1;
        }
        let sid = if length < 256 {
            // SAFETY: verified length belongs to the still-live returned string.
            String::from_utf16(unsafe { std::slice::from_raw_parts(text, length) }).ok()
        } else {
            None
        };
        // SAFETY: matching Windows allocation family.
        unsafe { LocalFree(text.cast()) };
        let sid = sid.ok_or_else(containment)?;
        let sddl = wide(OsStr::new(&format!(
            "D:P(A;OICI;GA;;;{user})(A;OICI;GA;;;SY)(A;OICI;GRGX;;;{sid})"
        )))?;
        let mut descriptor = null_mut();
        // SAFETY: valid SDDL and writable descriptor output, freed below.
        if unsafe {
            ConvertStringSecurityDescriptorToSecurityDescriptorW(
                sddl.as_ptr(),
                SDDL_REVISION_1,
                &raw mut descriptor,
                null_mut(),
            )
        } == 0
        {
            return Err(containment());
        }
        let mut present = 0;
        let mut defaulted = 0;
        let mut dacl = null_mut();
        // SAFETY: live descriptor; the resulting DACL remains live until both ACL updates finish.
        let valid = unsafe {
            GetSecurityDescriptorDacl(
                descriptor,
                &raw mut present,
                &raw mut dacl,
                &raw mut defaulted,
            )
        } != 0
            && present != 0
            && !dacl.is_null();
        let result = (|| {
            if !valid {
                return Err(containment());
            }
            for path in [
                directory.to_owned(),
                directory.join("ort-parser-helper.exe"),
            ] {
                let path = wide(path.as_os_str())?;
                // SAFETY: only the new, pinned helper stage receives this SID.
                // No profile, vault, source file or application-data ACL is changed.
                if unsafe {
                    SetNamedSecurityInfoW(
                        path.as_ptr(),
                        SE_FILE_OBJECT,
                        DACL_SECURITY_INFORMATION | PROTECTED_DACL_SECURITY_INFORMATION,
                        null_mut(),
                        null_mut(),
                        dacl,
                        null(),
                    )
                } != 0
                {
                    return Err(containment());
                }
            }
            Ok(())
        })();
        // SAFETY: descriptor came from ConvertStringSecurityDescriptor...
        unsafe { LocalFree(descriptor) };
        result
    }
    fn delete(&mut self) -> Result<()> {
        if !self.deleted {
            // SAFETY: unique profile name created by this instance, no shared app identity.
            if unsafe { DeleteAppContainerProfile(self.name.as_ptr()) } < 0 {
                return Err(ParserError::Cleanup);
            }
            self.deleted = true;
        }
        Ok(())
    }
}
impl Drop for Container {
    fn drop(&mut self) {
        let _ = self.delete();
        unsafe { FreeSid(self.sid) };
    }
}

struct Attributes {
    storage: Vec<usize>,
    initialized: bool,
}
impl Attributes {
    fn new() -> Result<Self> {
        let mut length = 0;
        // SAFETY: documented size query, followed by aligned backing storage.
        unsafe { InitializeProcThreadAttributeList(null_mut(), 5, 0, &raw mut length) };
        if length == 0 || length > 1024 * 1024 {
            return Err(containment());
        }
        let mut value = Self {
            storage: vec![0; length.div_ceil(size_of::<usize>())],
            initialized: false,
        };
        if unsafe {
            InitializeProcThreadAttributeList(
                value.storage.as_mut_ptr().cast(),
                5,
                0,
                &raw mut length,
            )
        } == 0
        {
            return Err(containment());
        }
        value.initialized = true;
        Ok(value)
    }
    // SAFETY: callers must keep value in its original address through CreateProcessW.
    unsafe fn set<T>(&mut self, key: u32, value: &T) -> Result<()> {
        if unsafe {
            UpdateProcThreadAttribute(
                self.storage.as_mut_ptr().cast(),
                0,
                key as usize,
                std::ptr::from_ref(value).cast(),
                size_of::<T>(),
                null_mut(),
                null(),
            )
        } == 0
        {
            return Err(containment());
        }
        Ok(())
    }
}
impl Drop for Attributes {
    fn drop(&mut self) {
        if self.initialized {
            // SAFETY: initialization succeeded and all backing storage remains live.
            unsafe { DeleteProcThreadAttributeList(self.storage.as_mut_ptr().cast()) };
        }
    }
}

struct Child {
    process: OwnedHandle,
    job: OwnedHandle,
    cleaned: bool,
}
impl Child {
    fn cleanup(&mut self) -> Result<()> {
        if self.cleaned {
            return Ok(());
        }
        // SAFETY: the job is never inherited and never allows breakaway.
        unsafe { TerminateJobObject(self.job.as_raw_handle(), 124) };
        let end = Instant::now() + CLEANUP;
        loop {
            let mut accounting = JOBOBJECT_BASIC_ACCOUNTING_INFORMATION::default();
            // SAFETY: valid process/job handles, correctly sized accounting output.
            let waited =
                unsafe { WaitForSingleObject(self.process.as_raw_handle(), 0) } == WAIT_OBJECT_0;
            let queried = unsafe {
                QueryInformationJobObject(
                    self.job.as_raw_handle(),
                    JobObjectBasicAccountingInformation,
                    (&raw mut accounting).cast(),
                    u32::try_from(size_of::<JOBOBJECT_BASIC_ACCOUNTING_INFORMATION>())
                        .map_err(|_| containment())?,
                    null_mut(),
                )
            } != 0;
            if waited && queried && accounting.ActiveProcesses == 0 {
                self.cleaned = true;
                return Ok(());
            }
            if Instant::now() >= end {
                return Err(ParserError::Cleanup);
            }
            std::thread::sleep(Duration::from_millis(1));
        }
    }
    fn exited(&self) -> Result<Option<u32>> {
        // SAFETY: owned live process handle remains valid after process exit.
        if unsafe { WaitForSingleObject(self.process.as_raw_handle(), 0) } != WAIT_OBJECT_0 {
            return Ok(None);
        }
        let mut code = 0;
        if unsafe { GetExitCodeProcess(self.process.as_raw_handle(), &raw mut code) } == 0 {
            return Err(ParserError::Io);
        }
        Ok(Some(code))
    }
}
impl Drop for Child {
    fn drop(&mut self) {
        let _ = self.cleanup();
    }
}

// Keep all five attribute backing values visibly alive through process creation.
#[allow(clippy::too_many_lines)]
fn launch(
    path: &Path,
    cwd: &Path,
    container: &Container,
    handles: &[InheritedEnd; 3],
) -> Result<Child> {
    // SAFETY: unnamed job handle is owned and non-inheritable.
    let job = unsafe { CreateJobObjectW(null(), null()) };
    if job.is_null() {
        return Err(containment());
    }
    let job = unsafe { OwnedHandle::from_raw_handle(job) };
    let mut limits = JOBOBJECT_EXTENDED_LIMIT_INFORMATION::default();
    limits.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE
        | JOB_OBJECT_LIMIT_ACTIVE_PROCESS
        | JOB_OBJECT_LIMIT_DIE_ON_UNHANDLED_EXCEPTION
        | JOB_OBJECT_LIMIT_PROCESS_MEMORY;
    limits.BasicLimitInformation.ActiveProcessLimit = 1;
    // Defense-in-depth native ceiling; the separate Wasm 512-MiB/fuel policy remains authoritative.
    limits.ProcessMemoryLimit = 1024 * 1024 * 1024;
    if unsafe {
        SetInformationJobObject(
            job.as_raw_handle(),
            JobObjectExtendedLimitInformation,
            (&raw const limits).cast(),
            u32::try_from(size_of::<JOBOBJECT_EXTENDED_LIMIT_INFORMATION>())
                .map_err(|_| containment())?,
        )
    } == 0
    {
        return Err(containment());
    }
    let capabilities = Box::new(SECURITY_CAPABILITIES {
        AppContainerSid: container.sid,
        Capabilities: null_mut(),
        CapabilityCount: 0,
        Reserved: 0,
    });
    let inherited = Box::new(handles.each_ref().map(|end| end.0.as_raw_handle()));
    let jobs = Box::new([job.as_raw_handle()]);
    let policy = Box::new(PROCESS_CREATION_CHILD_PROCESS_RESTRICTED);
    let mitigations = Box::new(MITIGATIONS);
    let mut attributes = Attributes::new()?;
    // SAFETY: boxed backing allocations remain alive until the attribute list
    // is explicitly destroyed below, after CreateProcessW returns on either path.
    unsafe {
        attributes.set(
            PROC_THREAD_ATTRIBUTE_SECURITY_CAPABILITIES,
            capabilities.as_ref(),
        )?;
        attributes.set(PROC_THREAD_ATTRIBUTE_HANDLE_LIST, inherited.as_ref())?;
        attributes.set(PROC_THREAD_ATTRIBUTE_JOB_LIST, jobs.as_ref())?;
        attributes.set(PROC_THREAD_ATTRIBUTE_CHILD_PROCESS_POLICY, policy.as_ref())?;
        attributes.set(
            PROC_THREAD_ATTRIBUTE_MITIGATION_POLICY,
            mitigations.as_ref(),
        )?;
    }
    let executable = wide(path.as_os_str())?;
    let cwd = wide(cwd.as_os_str())?;
    let mut command = vec![u16::from(b'"')];
    command.extend_from_slice(&executable[..executable.len() - 1]);
    command.push(u16::from(b'"'));
    command.push(0);
    let mut windows = vec![0_u16; 32_768];
    let length = unsafe { GetWindowsDirectoryW(windows.as_mut_ptr(), 32_768) };
    if length == 0 || length >= 32_768 {
        return Err(containment());
    }
    // Windows needs the real profile metadata to locate and virtualize the
    // AppContainer profile. Only these path values are allowlisted; no provider,
    // Codex, PATH, or arbitrary parent environment entries are inherited.
    let mut environment = Vec::new();
    for name in [
        "APPDATA",
        "LOCALAPPDATA",
        "SystemRoot",
        "TEMP",
        "TMP",
        "USERPROFILE",
        "WINDIR",
    ] {
        environment.extend(name.encode_utf16());
        environment.push(u16::from(b'='));
        if matches!(name, "SystemRoot" | "WINDIR") {
            environment.extend_from_slice(&windows[..length as usize]);
        } else if matches!(name, "APPDATA" | "LOCALAPPDATA" | "USERPROFILE") {
            let value = std::env::var_os(name).ok_or_else(containment)?;
            environment.extend(value.encode_wide());
        } else {
            environment.extend_from_slice(&cwd[..cwd.len() - 1]);
        }
        environment.push(0);
    }
    environment.push(0);
    let mut startup = STARTUPINFOEXW::default();
    startup.StartupInfo.cb =
        u32::try_from(size_of::<STARTUPINFOEXW>()).map_err(|_| containment())?;
    startup.StartupInfo.dwFlags = STARTF_USESTDHANDLES;
    [
        startup.StartupInfo.hStdInput,
        startup.StartupInfo.hStdOutput,
        startup.StartupInfo.hStdError,
    ] = *inherited;
    startup.lpAttributeList = attributes.storage.as_mut_ptr().cast();
    let mut information = PROCESS_INFORMATION::default();
    // SAFETY: explicitly bounded environment and exactly three inherited handles;
    // the job is assigned atomically at creation, and the first thread is suspended.
    let created = unsafe {
        CreateProcessW(
            executable.as_ptr(),
            command.as_mut_ptr(),
            null(),
            null(),
            1,
            EXTENDED_STARTUPINFO_PRESENT
                | CREATE_SUSPENDED
                | CREATE_UNICODE_ENVIRONMENT
                | CREATE_NO_WINDOW,
            environment.as_ptr().cast(),
            cwd.as_ptr(),
            &raw const startup.StartupInfo,
            &raw mut information,
        )
    };
    drop(attributes);
    drop((capabilities, inherited, jobs, policy, mitigations));
    if created == 0 {
        return Err(containment());
    }
    let mut child = Child {
        process: unsafe { OwnedHandle::from_raw_handle(information.hProcess) },
        job,
        cleaned: false,
    };
    let thread = unsafe { OwnedHandle::from_raw_handle(information.hThread) };
    if let Err(error) = verify_running(&child, path, container.sid) {
        child.cleanup()?;
        return Err(error);
    }
    if unsafe { ResumeThread(thread.as_raw_handle()) } == u32::MAX {
        child.cleanup()?;
        return Err(containment());
    }
    Ok(child)
}

fn verify_running(child: &Child, path: &Path, expected_sid: PSID) -> Result<()> {
    let mut token = null_mut();
    // SAFETY: read-only query of our suspended child's token, never inherited.
    if unsafe { OpenProcessToken(child.process.as_raw_handle(), TOKEN_QUERY, &raw mut token) } == 0
    {
        return Err(containment());
    }
    let token = unsafe { OwnedHandle::from_raw_handle(token) };
    let mut buffer = [0_u64; 128];
    let mut length = 0;
    for class in [TokenIsAppContainer, TokenCapabilities, TokenAppContainerSid] {
        buffer.fill(0);
        if unsafe {
            GetTokenInformation(
                token.as_raw_handle(),
                class,
                buffer.as_mut_ptr().cast(),
                u32::try_from(size_of_val(&buffer)).map_err(|_| containment())?,
                &raw mut length,
            )
        } == 0
        {
            return Err(containment());
        }
        // SAFETY: GetTokenInformation initialized aligned storage for the requested class.
        let valid = unsafe {
            if class == TokenIsAppContainer {
                *buffer.as_ptr().cast::<u32>() == 1
            } else if class == TokenCapabilities {
                (*buffer.as_ptr().cast::<TOKEN_GROUPS>()).GroupCount == 0
            } else {
                EqualSid(
                    (*buffer.as_ptr().cast::<TOKEN_APPCONTAINER_INFORMATION>()).TokenAppContainer,
                    expected_sid,
                ) != 0
            }
        };
        if !valid {
            return Err(containment());
        }
    }
    let mut member = 0;
    let mut policy = PROCESS_MITIGATION_CHILD_PROCESS_POLICY::default();
    if unsafe {
        IsProcessInJob(
            child.process.as_raw_handle(),
            child.job.as_raw_handle(),
            &raw mut member,
        )
    } == 0
        || member == 0
        || unsafe {
            GetProcessMitigationPolicy(
                child.process.as_raw_handle(),
                ProcessChildProcessPolicy,
                (&raw mut policy).cast(),
                size_of::<PROCESS_MITIGATION_CHILD_PROCESS_POLICY>(),
            )
        } == 0
        || unsafe { policy.Anonymous.Flags } != 1
    {
        return Err(containment());
    }
    let mut image = vec![0_u16; 32_768];
    for class in [
        ProcessDynamicCodePolicy,
        ProcessExtensionPointDisablePolicy,
        ProcessSystemCallDisablePolicy,
    ] {
        let mut flags = 0_u32;
        // SAFETY: each selected policy is a documented DWORD flags structure.
        // Require the exact prohibition, including absence of dynamic-code
        // opt-out/remote-downgrade or audit-only flags.
        if unsafe {
            GetProcessMitigationPolicy(
                child.process.as_raw_handle(),
                class,
                (&raw mut flags).cast(),
                size_of::<u32>(),
            )
        } == 0
            || flags != 1
        {
            return Err(containment());
        }
    }
    let mut size = 32_768;
    if unsafe {
        QueryFullProcessImageNameW(
            child.process.as_raw_handle(),
            0,
            image.as_mut_ptr(),
            &raw mut size,
        )
    } == 0
    {
        return Err(ParserError::Identity);
    }
    let image = std::path::PathBuf::from(std::ffi::OsString::from_wide(&image[..size as usize]));
    if image.canonicalize().map_err(|_| ParserError::Identity)?
        != path.canonicalize().map_err(|_| ParserError::Identity)?
    {
        return Err(ParserError::Identity);
    }
    Ok(())
}

/// Native composition supplies the compiled package hash; never accept these
/// parameters from renderer IPC. Output is untrusted until decoded by ort-documents.
pub struct ContainedParser;
impl ContainedParser {
    /// # Errors
    /// Refuses unverified images, failed containment, deadline/cancellation,
    /// oversized output, nonzero exit, and any unconfirmed cleanup.
    pub fn exchange(
        path: &Path,
        expected: &[u8; 32],
        request: &[u8],
        end: Instant,
        cancel: &AtomicBool,
    ) -> Result<Vec<u8>> {
        run(
            path,
            expected,
            request,
            end.min(Instant::now() + Duration::from_secs(60)),
            cancel,
        )
    }
}

fn run(
    path: &Path,
    expected: &[u8; 32],
    request: &[u8],
    end: Instant,
    cancel: &AtomicBool,
) -> Result<Vec<u8>> {
    if request.is_empty() || request.len() > MAX_REQUEST {
        return Err(ParserError::Io);
    }
    check(end, cancel)?;
    let _source_guards = reject_reparse_path(path).map_err(|_| ParserError::Identity)?;
    let mut source = OpenOptions::new()
        .read(true)
        .share_mode(FILE_SHARE_READ)
        .open(path)
        .map_err(|_| ParserError::Identity)?;
    let length = source.metadata().map_err(|_| ParserError::Identity)?.len();
    if length == 0 || length > MAX_EXECUTABLE {
        return Err(ParserError::Identity);
    }
    let mut container = Container::new()?;
    let profile_directory = container.folder()?;
    let stage =
        PrivateDirectory::create(&profile_directory.join("worker")).map_err(|_| containment())?;
    let executable = stage.path().join("ort-parser-helper.exe");
    let mut destination = OpenOptions::new()
        .create_new(true)
        .write(true)
        .open(&executable)
        .map_err(|_| ParserError::Io)?;
    let mut hash = Sha256::new();
    let mut buffer = vec![0; 64 * 1024];
    let mut total = 0;
    loop {
        check(end, cancel)?;
        let count = source
            .read(&mut buffer)
            .map_err(|_| ParserError::Identity)?;
        if count == 0 {
            break;
        }
        total += count as u64;
        if total > MAX_EXECUTABLE {
            return Err(ParserError::Identity);
        }
        hash.update(&buffer[..count]);
        destination
            .write_all(&buffer[..count])
            .map_err(|_| ParserError::Io)?;
    }
    if total != length || hash.finalize().as_slice() != expected {
        return Err(ParserError::Identity);
    }
    destination.sync_all().map_err(|_| ParserError::Io)?;
    drop(destination);
    let locked_image = OpenOptions::new()
        .read(true)
        .share_mode(FILE_SHARE_READ)
        .open(&executable)
        .map_err(|_| ParserError::Identity)?;
    container.grant_read(stage.path())?;
    let (stdin, child_in) = inherited_pair().map_err(|_| ParserError::Io)?;
    let (stdout, child_out) = inherited_pair().map_err(|_| ParserError::Io)?;
    let (stderr, child_err) = inherited_pair().map_err(|_| ParserError::Io)?;
    check(end, cancel)?;
    let ends = [child_in, child_out, child_err];
    let mut child = launch(&executable, stage.path(), &container, &ends)?;
    drop(ends);
    let result = exchange_io(&child, stdin, &stdout, &stderr, request, end, cancel);
    child.cleanup()?;
    drop(child);
    drop(locked_image);
    drop(stage);
    // The unique profile contains only the helper and its own initially empty
    // state. No source document is written there; deletion still needs confirmation.
    container.delete()?;
    if profile_directory
        .try_exists()
        .map_err(|_| ParserError::Cleanup)?
    {
        return Err(ParserError::Cleanup);
    }
    drop(container);
    result.and_then(|output| {
        check(end, cancel)?;
        Ok(output)
    })
}

fn exchange_io(
    child: &Child,
    stdin: PipeConnection,
    stdout: &PipeConnection,
    stderr: &PipeConnection,
    request: &[u8],
    end: Instant,
    cancel: &AtomicBool,
) -> Result<Vec<u8>> {
    let mut stdin = Some(stdin);
    let mut sent = 0;
    let mut writer: Option<PipeOperation> = None;
    let mut readers = [
        Some(stdout.read().map_err(|_| ParserError::Io)?),
        Some(stderr.read().map_err(|_| ParserError::Io)?),
    ];
    let mut output = Vec::new();
    let mut stderr_bytes = 0;
    let result = (|| {
        loop {
            check(end, cancel)?;
            if let Some(write) = &mut writer
                && let Some(count) = write.poll().map_err(|_| ParserError::Io)?
            {
                if count == 0 {
                    return Err(ParserError::Io);
                }
                sent += count;
                writer = None;
            }
            if writer.is_none() {
                if sent == request.len() {
                    stdin = None;
                } else if let Some(input) = &stdin {
                    writer = Some(
                        input
                            .write(&request[sent..request.len().min(sent + 8192)])
                            .map_err(|_| ParserError::Io)?,
                    );
                }
            }
            for (index, stream) in [stdout, stderr].into_iter().enumerate() {
                let Some(read) = &mut readers[index] else {
                    continue;
                };
                if let Some(count) = read.poll().map_err(|_| ParserError::Io)? {
                    if count == 0 {
                        readers[index] = None;
                        continue;
                    }
                    if index == 0 {
                        if output.len() + count > MAX_OUTPUT {
                            return Err(ParserError::Io);
                        }
                        output.extend_from_slice(read.bytes().map_err(|_| ParserError::Io)?);
                    } else {
                        stderr_bytes += count;
                        if stderr_bytes > MAX_STDERR {
                            return Err(ParserError::Io);
                        }
                    }
                    readers[index] = Some(stream.read().map_err(|_| ParserError::Io)?);
                }
            }
            if let Some(code) = child.exited()? {
                if code != 0 || sent != request.len() {
                    #[cfg(feature = "test-support")]
                    eprintln!("synthetic parser fixture exit: {code:#x}");
                    return Err(ParserError::Io);
                }
                if readers.iter().all(Option::is_none) {
                    check(end, cancel)?;
                    return Ok(output);
                }
            }
            std::thread::sleep(Duration::from_millis(1));
        }
    })();
    let mut cleaned = true;
    for operation in writer.into_iter().chain(readers.into_iter().flatten()) {
        cleaned &= operation.cancel().is_ok();
    }
    if cleaned {
        result
    } else {
        Err(ParserError::Cleanup)
    }
}
